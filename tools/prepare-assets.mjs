import {readFile, readdir, writeFile, stat} from 'node:fs/promises';
import {fileURLToPath} from 'node:url';
import {theme} from '../dist/v1.2.0/theme.js';
const root=new URL('../dist/',import.meta.url), versionRoot=new URL('v1.2.0/',root);
if(theme.length!==6)throw Error('Exactly six block entries are required');
for(const item of theme){
  if(!item.image)continue;
  const image=new URL(item.image,versionRoot);
  if(!image.href.startsWith(versionRoot.href)||image.search||image.hash)throw Error('Block images must be local files inside v1.2.0/');
  if(!/\.(png|webp|svg|jpe?g)$/i.test(image.pathname)||!(await stat(fileURLToPath(image))).isFile())throw Error('Missing or unsupported block image: '+item.image);
}
const files=[];
async function walk(directory,prefix){for(const entry of (await readdir(directory,{withFileTypes:true})).sort((a,b)=>a.name.localeCompare(b.name))){if(entry.name.startsWith('.'))throw Error('Unexpected hidden file');if(entry.name==='asset-list.js')continue;const path=prefix+entry.name;if(entry.isDirectory())await walk(new URL(entry.name+'/',directory),path+'/');else files.push('./'+path);}}
await walk(versionRoot,'v1.2.0/');
const assets=['./','./index.html','./v1.2.0/asset-list.js',...files];
await writeFile(new URL('asset-list.js',versionRoot),'// Generated by npm run prepare. Do not edit.\nself.PRECACHE_FILES = '+JSON.stringify(assets,null,2)+';\n');
console.log(`Prepared ${theme.filter(item=>item.image).length} configured block images; ${assets.length} cached URLs.`);
